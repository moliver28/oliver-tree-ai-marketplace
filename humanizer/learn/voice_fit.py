#!/usr/bin/env python3
"""voice_fit.py: advisory voice-fit table (count-based stylometry, zero LLM).

One advisory unit for the two count-based stylometry layers that already
existed separately in learn/: Burrows' Delta (M15, acceptance_check.py
Signal A) and the surface statistics (M18, build_voice_profile.py). The math
is promotion, not invention: the same formulas, the P18 refinements from the
sitefactory journalism template (moliver28/sitefactory,
templates/journalism/template/scripts/linkcheck-args.cjs @ 9dfb5cf, the
marker-delimited portable stylometry block):

- Fail-open: with no client sample and no profile the table still renders the
  candidate column plus a defined note, exit 0. Bad usage alone exits 2.
- One actionable row per metric: sample column vs candidate column, then the
  Burrows' Delta row ("lower = closer"), then the length-confidence note.
- Tokenizer shared with the gate: WORD_RE from build_voice_profile.py, the
  same [A-Za-z0-9']+ charset the ASD-STE100 layer counts.
- Contract tests pin the numbers: humanizer/tests/test_voice_fit.py asserts
  exact-equal outputs against the committed sitefactory fixture
  (tests/fixtures/sitefactory_p18.json, generated by running the sitefactory
  block itself).

Boundary (the plugin's separation of powers, unchanged):
- This module NEVER runs in the delivery gate. hooks/gate.py is untouched by
  it; the gate's blocking path carries regex tells + ASD-STE100 only.
- Advisory only: the table reports numbers and notes, never a verdict, never
  a threshold, never a block. Voice-fit measurement (does the copy sit near
  the client's sample), NOT AI detection.
- stdlib only (argparse, importlib.util, json, math, os, re, sys, pathlib);
  no embeddings, no perplexity, no classifier.

Reliability: Burrows' Delta firms up near ~5,000 words and is usable from
about 1,500-2,000 (Eder 2015/2017). Below that the table says so in a note;
no length ever hard-fails anything.

Delta needs spread: a profile built from fewer than 2 sample documents has
every stddev at 0, and fewer than 3 sample documents cannot produce the
leave-one-out sample-self number; both render as n/a.

Usage:
    python3 voice_fit.py CANDIDATE [--samples PATH] [--profile PATH] [--json]
    CANDIDATE: a file path, or '-' to read stdin.
    --samples: the client's writing samples, a directory or a single
               .md/.txt file (same input contract as build_voice_profile.py).
               Give either --samples or a built profile; both is best
               (sample column from the samples, Delta against their profile).
    --profile: learned/profile.json path (default: the plugin learned dir,
               VOICE_LEARNED_DIR override honored).
Exit codes: 0 = table printed (advisory, fail-open); 2 = bad usage.
"""
import argparse
import importlib.util
import json
import math
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent          # humanizer/learn/
PLUGIN_DIR = HERE.parent                        # humanizer/

# WORD_RE, SENT_SPLIT, PASSIVE_RE, INTENSIFIER_RE and FUNCTION_WORDS live in
# build_voice_profile.py (single source of truth, shared with acceptance_check.py).
# WORD_RE is also the charset the delivery gate's ASD-STE100 layer counts, so
# the advisory table and the gate tokenize alike.
_bvp_spec = importlib.util.spec_from_file_location(
    "voice_profile_fit", HERE / "build_voice_profile.py")
bvp = importlib.util.module_from_spec(_bvp_spec)
_bvp_spec.loader.exec_module(bvp)
WORD_RE = bvp.WORD_RE
SENT_SPLIT = bvp.SENT_SPLIT
PASSIVE_RE = bvp.PASSIVE_RE
INTENSIFIER_RE = bvp.INTENSIFIER_RE
FUNCTION_WORDS = bvp.FUNCTION_WORDS

READER_ADDRESS_RE = re.compile(r"\b(you|your)\b", re.IGNORECASE)

# The sitefactory punctuation set: six marks, counted on the whole text with
# the same leftmost alternation the JS block uses. (build_voice_profile.py's
# own punctuation table is wider — periods, commas, close paren — and feeds
# the profile; this narrower set is the sitefactory-parity view.)
PUNCT_MATCHERS = [
    ("questions per 1k words", re.compile(r"\?")),
    ("exclamations per 1k words", re.compile(r"!")),
    ("semicolons per 1k words", re.compile(r";")),
    ("colons per 1k words", re.compile(r":")),
    ("dashes per 1k words", re.compile(r"—|--")),
    ("parens per 1k words", re.compile(r"\(")),
]

STAT_KEYS = [
    "word count", "sentences",
    "sentence length mean", "sentence length median", "sentence length p95",
    *[label for label, _ in PUNCT_MATCHERS],
    "passive sentence share", "intensifiers per 100 words", "reader-address share",
]


def _js_round(x):
    """ECMA-262 Math.round for non-negative doubles: floor(x + 0.5). The
    sitefactory block rounds every reported stat with Math.round, so the
    Python side must round identically for the parity pin to hold (Python's
    built-in round() is banker's rounding and differs on ties)."""
    return math.floor(x + 0.5)


def _round_stat(x, m):
    """Math.round(x * m) / m with JS number semantics: an integral result
    stays an int (JSON.stringify renders 0 as 0, not 0.0)."""
    n = _js_round(x)
    return n // m if n % m == 0 else n / m


def words(text):
    return [w.lower() for w in WORD_RE.findall(text)]


def sentences(text):
    return [s for s in SENT_SPLIT.split(text.strip()) if s.strip()]


def median(xs):
    s = sorted(xs)
    n = len(s)
    if not n:
        return 0
    mid = n // 2
    if n % 2:
        return s[mid]
    total = s[mid - 1] + s[mid]
    return total // 2 if total % 2 == 0 else total / 2


def percentile(xs, q):
    s = sorted(xs)
    return s[max(0, math.ceil(q * len(s)) - 1)] if s else 0


def voice_stats(text):
    """The M18 advisory subset with sitefactory-parity keys, key order and
    rounding. Exact-equal to the sitefactory voiceStats() on digit-free
    ASCII text (pinned by the committed fixture)."""
    sents = sentences(text)
    lens = [len(words(s)) for s in sents]
    toks = words(text)
    total = len(toks)
    n_sents = len(sents)

    def rate(n, per):
        return _round_stat(((n * per) / total) * 100, 100) if total else 0

    stats = {
        "word count": total,
        "sentences": n_sents,
        "sentence length mean": _round_stat((sum(lens) / len(lens)) * 100, 100) if lens else 0,
        "sentence length median": median(lens),
        "sentence length p95": percentile(lens, 0.95),
    }
    for label, rx in PUNCT_MATCHERS:
        stats[label] = rate(len(rx.findall(text)), 1000)
    stats["passive sentence share"] = (
        _round_stat((sum(1 for s in sents if PASSIVE_RE.search(s)) / n_sents) * 1000, 1000)
        if n_sents else 0)
    stats["intensifiers per 100 words"] = rate(len(INTENSIFIER_RE.findall(text)), 100)
    stats["reader-address share"] = (
        _round_stat((sum(1 for s in sents if READER_ADDRESS_RE.search(s)) / n_sents) * 1000, 1000)
        if n_sents else 0)
    return stats


def function_rates(text):
    """Per-1000-words rate of each profile function word (unrounded, the same
    quantity the sitefactory functionRates() and the Burrows' Delta profile
    consume)."""
    toks = words(text)
    counts = {w: 0 for w in FUNCTION_WORDS}
    for w in toks:
        if w in counts:
            counts[w] += 1
    base = len(toks)
    return {w: (counts[w] * 1000.0) / base if base else 0.0 for w in FUNCTION_WORDS}


def delta(rate, docs):
    """Burrows' Delta against per-document rate rows (the sitefactory shape):
    mean absolute z-score over profile words whose cross-document stddev > 0
    (population stddev). Returns None when no word qualifies (no spread — the
    sitefactory block returns NaN there; the table renders n/a)."""
    zs = []
    for w in FUNCTION_WORDS:
        col = [d[w] for d in docs]
        mu = sum(col) / len(col)
        sd = math.sqrt(sum((x - mu) ** 2 for x in col) / len(col))
        if sd > 0:
            zs.append(abs((rate[w] - mu) / sd))
    return sum(zs) / len(zs) if zs else None


def burrows_delta(text, fw):
    """Burrows' Delta against a built profile's function_words section (the
    upstream acceptance_check.py shape, mirrored line for line so the two
    tools stay one math source; the contract test asserts equal outputs).
    Returns (delta, word_count); delta is 0.0 when no word qualifies."""
    toks = words(text)
    n = len(toks)
    counts = {}
    for w in toks:
        counts[w] = counts.get(w, 0) + 1
    mean, sd = fw["mean"], fw["stddev"]
    zs = []
    for w in fw["words"]:
        s = sd.get(w, 0.0)
        if s and s > 0:
            f = counts.get(w, 0) * 1000.0 / n if n else 0.0
            zs.append(abs((f - mean.get(w, 0.0)) / s))
    return (sum(zs) / len(zs) if zs else 0.0), n


def sample_self_delta(docs):
    """Leave-one-out mean of each sample document's Delta against the rest of
    the sample corpus (the sitefactory sample-self column). None under three
    documents: with fewer, one document cannot sit out and a two-document
    remainder carries no spread to average over."""
    if len(docs) < 3:
        return None
    vals = [delta(docs[i], docs[:i] + docs[i + 1:]) for i in range(len(docs))]
    vals = [v for v in vals if v is not None]
    return sum(vals) / len(vals) if vals else None


def load_samples(path):
    """Expand --samples to a deterministic, sorted list of .md/.txt files
    (a directory walks recursively; a single file passes through). Empty
    result -> SystemExit(2) with the defined message."""
    p = Path(path).expanduser()
    files = []
    if p.is_dir():
        for cand in sorted(p.rglob("*")):
            if cand.is_file() and cand.suffix.lower() in (".md", ".txt"):
                files.append(cand)
    elif p.is_file() and p.suffix.lower() in (".md", ".txt"):
        files.append(p)
    if not files:
        print(f'usage: --samples path "{path}" is missing or holds no .md/.txt files',
              file=sys.stderr)
        raise SystemExit(2)
    return files


def learned_profile_path():
    """Default profile path; VOICE_LEARNED_DIR overrides (same contract as
    acceptance_check.py)."""
    return Path(os.environ.get("VOICE_LEARNED_DIR", PLUGIN_DIR / "learned")) / "profile.json"


def profile_stats(profile):
    """The sample column in profile mode, mapped from profile.json's own
    aggregate sections onto the sitefactory stat keys (missing fields map to
    None and render n/a). The em-dash and double-hyphen profile rates sum to
    the sitefactory single dashes rate: the two counts never overlap."""
    sl = profile.get("sentence_length") or {}
    pu = profile.get("punctuation_per_1000_words") or {}
    dashes = pu.get("em dash")
    dash2 = pu.get("double hyphen")
    return {
        "word count": profile.get("words"),
        "sentences": profile.get("sentences"),
        "sentence length mean": sl.get("mean"),
        "sentence length median": sl.get("median"),
        "sentence length p95": sl.get("p95"),
        "questions per 1k words": pu.get("question"),
        "exclamations per 1k words": pu.get("exclamation"),
        "semicolons per 1k words": pu.get("semicolon"),
        "colons per 1k words": pu.get("colon"),
        "dashes per 1k words": (dashes + dash2) if isinstance(dashes, (int, float))
        and isinstance(dash2, (int, float)) else None,
        "parens per 1k words": pu.get("open paren"),
        "passive sentence share": profile.get("passive_sentence_share"),
        "intensifiers per 100 words": profile.get("intensifiers_per_100_words"),
        "reader-address share": profile.get("reader_address_share"),
    }


def load_profile(path):
    """Read profile.json; returns (profile_or_None, note_or_None). Fail-open:
    an absent or unreadable profile degrades the table, it never fails the run."""
    p = Path(path).expanduser()
    if not p.is_file():
        return None, f"note: no profile at {p}; delta and the sample column read n/a (run learn/build_voice_profile.py, or pass --samples DIR)."
    try:
        prof = json.loads(p.read_text(encoding="utf-8"))
    except Exception as e:
        return None, f"note: profile at {p} unreadable ({e!r}); delta and the sample column read n/a."
    if not isinstance(prof, dict) or not isinstance(prof.get("function_words"), dict):
        return None, f"note: profile at {p} has no function_words section; delta reads n/a (rebuild it with learn/build_voice_profile.py)."
    return prof, None


def length_note(sample_stats, copy_stats):
    """The P18 confidence note. Delta firms up near ~5,000 words and is
    usable from ~1,500-2,000 (Eder 2015/2017); under 1,500 a side, the whole
    table is rough. Never a gate at any length."""
    wc_s = sample_stats.get("word count") if sample_stats else None
    wc_c = copy_stats.get("word count") if copy_stats else None
    sides = [w for w in (wc_s, wc_c) if isinstance(w, int) and w > 0]
    if not sides:
        return None
    m = min(sides)
    if m < 1500:
        return "note: under ~1,500 words on a side; read these as rough."
    if m < 5000:
        return ("note: burrows_delta firms up near ~5,000 words (usable from about "
                "1,500-2,000); treat these numbers as directional until the corpus grows.")
    return None


def _js_str(v):
    """Render one stat the way the sitefactory rows do (integer-valued
    numbers without a decimal point; n/a for missing)."""
    if v is None or not isinstance(v, (int, float)):
        return "n/a"
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def _fmt(v):
    """The sitefactory delta formatter: two decimals, n/a when absent."""
    if v is None or not isinstance(v, (int, float)):
        return "n/a"
    r = _js_round(v * 100) / 100
    return str(int(r)) if float(r).is_integer() else str(r)


def fit_table(sample_stats, copy_stats, sample_self, copy_delta, extra_notes):
    """Render the advisory table: one row per metric, then the Delta row."""
    lines = ["voice fit: client sample vs candidate copy"]
    for k in STAT_KEYS:
        s = _js_str(sample_stats.get(k)) if sample_stats else "n/a"
        lines.append(f"  {k}  sample {s}  copy {_js_str(copy_stats.get(k))}")
    lines.append(f"burrows_delta   sample-self {_fmt(sample_self)}   "
                 f"copy {_fmt(copy_delta)}   lower = closer")
    lines.extend(n for n in extra_notes if n)
    return "\n".join(lines) + "\n"


def build_report(candidate_text, sample_files, profile, profile_note):
    """Assemble (table_text, report_json_dict) for one candidate."""
    copy_stats = voice_stats(candidate_text)
    docs = None
    sample_stats = None
    sample_self = None
    copy_delta = None
    reference = None
    notes = [profile_note] if profile_note else []
    if sample_files:
        texts = [f.read_text(encoding="utf-8", errors="replace") for f in sample_files]
        sample_stats = voice_stats("\n\n".join(texts))
        docs = [function_rates(t) for t in texts]
        sample_self = sample_self_delta(docs)
        copy_delta = delta(function_rates(candidate_text), docs) if copy_stats["word count"] else None
        reference = "samples"
    elif profile:
        sample_stats = profile_stats(profile)
        fw = profile["function_words"]
        if isinstance(fw.get("docs"), int) and fw["docs"] >= 2:
            copy_delta = burrows_delta(candidate_text, fw)[0] if copy_stats["word count"] else None
            reference = "profile"
        else:
            notes.append("note: the profile carries fewer than 2 documents, so its function-word "
                         "spread is zero and delta reads n/a (add samples, rebuild the profile).")
    else:
        if not profile_note:
            notes.append("note: delta reads n/a with no client reference "
                         "(pass --samples DIR, or build learned/profile.json).")
    note = length_note(sample_stats, copy_stats)
    if note:
        notes.append(note)
    table = fit_table(sample_stats, copy_stats, sample_self, copy_delta, notes)
    report = {
        "candidate": copy_stats,
        "sample": sample_stats,
        "burrows_delta": {"sample_self": sample_self, "copy": copy_delta,
                          "unit": "mean absolute z-score; lower = closer"},
        "reference": reference,
        "notes": notes,
    }
    return table, report


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    as_json = "--json" in argv
    argv = [a for a in argv if a != "--json"]
    parser = argparse.ArgumentParser(
        prog="voice_fit.py",
        description="Advisory voice-fit table: Burrows' Delta + surface stats vs the client sample (never gates).")
    parser.add_argument("candidate", help="candidate file path, or '-' for stdin")
    parser.add_argument("--samples", default=None, help="client sample dir or .md/.txt file")
    parser.add_argument("--profile", default=None, help="learned/profile.json path (default: the plugin learned dir)")
    args = parser.parse_args(argv)
    if args.candidate == "-":
        candidate_text = sys.stdin.read()
        if not candidate_text.strip():
            print("usage: pipe text to stdin, or name a candidate file", file=sys.stderr)
            return 2
    else:
        p = Path(args.candidate).expanduser()
        if not p.is_file():
            print(f"usage: candidate file not found: {p}", file=sys.stderr)
            return 2
        candidate_text = p.read_text(encoding="utf-8", errors="replace")

    sample_files = load_samples(args.samples) if args.samples else None
    profile, profile_note = (None, None)
    if not sample_files:
        profile, profile_note = load_profile(args.profile or learned_profile_path())
    table, report = build_report(candidate_text, sample_files, profile, profile_note)
    if as_json:
        print(json.dumps(report, indent=2))
    else:
        sys.stdout.write(table)
    return 0


if __name__ == "__main__":
    sys.exit(main())
