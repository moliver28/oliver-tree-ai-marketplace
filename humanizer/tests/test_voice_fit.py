#!/usr/bin/env python3
"""Contract tests for learn/voice_fit.py (the advisory voice-fit table).

Run: python3 humanizer/tests/test_voice_fit.py
Also invoked by scripts/verify.py. Exit 0 = every contract gate green.

The contract this file pins (the P18 promotion of M15 + M18, extended by the
map findings AM-01 to AM-06 of 1.2.0):

1. Sitefactory parity: voice_stats / function_rates reproduce the committed
   fixture exactly (values AND number types). The fixture was generated by
   running the sitefactory P18 portable stylometry block itself
   (moliver28/sitefactory, linkcheck-args.cjs @ 9dfb5cf), so a green run
   means the Python port computes the same numbers as the source block.
   The delta functions deliberately DROPPED that parity in 1.2.0: the map's
   findings AM-04 (sample stddev), AM-06 (count floor), AM-03 (no spread
   reads n/a, never 0.0), AM-01 (the sample-self row prints k and the
   leave-one-out range), and AM-02 (delta rows suppressed below 500
   candidate words, windowed outside 0.5 to 2 times the median reference
   length) change the math on purpose. Section 1 below pins the NEW
   goldens and records the old values in comments.
2. Upstream equivalence: burrows_delta() matches acceptance_check.py Signal A
   on the same input and profile dict (one math source, two entry points).
3. Gate no-op: hooks/gate.py emits no stylometry fields and its clean-pass
   output stays byte-identical; the advisory module never enters the
   blocking path.
4. Fail-open: with no client sample and no profile the CLI still exits 0,
   renders the candidate column, and reads the reference columns n/a with a
   defined note; --json carries nulls.
5. Spread rule: a one-document sample yields n/a deltas (delta needs
   spread); a short candidate reads n/a with the owned 500-word floor note.
6. Tokenizer tolerance: on digit-free text the upstream WORD_RE and the
   sitefactory JS tokenizer agree token for token; digit runs are the one
   documented divergence and the fixture pins the exact difference.
7. stdlib-only: the module's imports never leave the stdlib set.
"""
import ast
import importlib.util
import json
import math
import os
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent      # humanizer/tests/
PLUGIN_DIR = HERE.parent                            # humanizer/
REPO_ROOT = PLUGIN_DIR.parent
FIXTURE = HERE / "fixtures" / "sitefactory_p18.json"
ALLOWED_IMPORTS = {"argparse", "importlib", "json", "math", "os", "re", "sys", "pathlib"}

fails = []


def ck(cond, name, detail=""):
    if cond:
        print(f"OK   {name}")
    else:
        print(f"FAIL {name}" + (f" ({detail})" if detail else ""))
        fails.append(name)


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


fx = json.loads(FIXTURE.read_text(encoding="utf-8"))
vf = load_module("voice_fit_contract", PLUGIN_DIR / "learn" / "voice_fit.py")
ac = load_module("acceptance_check_contract", PLUGIN_DIR / "learn" / "acceptance_check.py")

# 1. Sitefactory parity, exact values and types -------------------------------
vs = vf.voice_stats(fx["candidate_text"])
ck(list(vs) == list(fx["voice_stats"]), "parity: stat key order matches the sitefactory block")
diff = [(k, vs.get(k), fx["voice_stats"][k]) for k in fx["voice_stats"]
        if vs.get(k) != fx["voice_stats"][k] or type(vs.get(k)) is not type(fx["voice_stats"][k])]
ck(not diff, "parity: voice_stats reproduces the sitefactory block exactly", str(diff[:3]))
fr = vf.function_rates(fx["candidate_text"])
ck(fr == fx["function_rates"], "parity: function_rates reproduces functionRates() exactly (60 words)")
# Delta goldens moved in 1.2.0 (map findings AM-01 to AM-06): the delta math
# is now sample stddev (AM-04) plus the count floor s_eff (AM-06), and the
# sample-self row carries k and its leave-one-out range (AM-01). Old values
# (population stddev, no floor; kept in the fixture as the sitefactory
# block's record): copy_vs_docs 0.6745024700672055, per-doc leave-one-out
# [0.9140271493212669, 1.1857142857142857, 1.4561403508771928],
# sample_self mean 1.1852939286375819.
NEW_COPY_DELTA = 0.5225705576206382          # golden, Python 3.11.15 run
NEW_LOO = [0.47743987181161884, 0.5273983587126476, 0.5949932514834823]
CAND_WORDS = 122                              # WORD_RE tokens of candidate_text
DOC_WORDS = [13, 10, 13]
d, used = vf.delta(vf.function_rates(fx["candidate_text"]), fx["docs_rates"], CAND_WORDS)
ck(d == NEW_COPY_DELTA and used == 24,
   "promoted math: copy delta pin (sample stddev + count floor; was 0.6745024700672055)")
loo = [vf.delta(fx["docs_rates"][i], fx["docs_rates"][:i] + fx["docs_rates"][i + 1:], DOC_WORDS[i])[0]
       for i in range(len(fx["docs_rates"]))]
ck(loo == NEW_LOO, "promoted math: per-document leave-one-out deltas bit-equal "
                   "(was [0.9140271493212669, 1.1857142857142857, 1.4561403508771928])")
ss = vf.sample_self_delta(fx["docs_rates"], DOC_WORDS)
ck(ss == {"mean": 0.5332771606692496, "k": 3,
          "min": 0.47743987181161884, "max": 0.5949932514834823},
   "promoted math: sample-self row carries mean, k, and the loo range (old mean 1.1852939286375819)")

# 2. Upstream equivalence with acceptance_check.py ----------------------------
mean = {w: sum(r[w] for r in fx["docs_rates"]) / len(fx["docs_rates"]) for w in vf.FUNCTION_WORDS}
stddev = {w: math.sqrt(sum((r[w] - mean[w]) ** 2 for r in fx["docs_rates"]) / (len(fx["docs_rates"]) - 1))
          for w in vf.FUNCTION_WORDS}
fw = {"words": list(vf.FUNCTION_WORDS), "mean": mean, "stddev": stddev}
ck(vf.burrows_delta(fx["candidate_text"], fw) == ac.burrows_delta(fx["candidate_text"], fw),
   "upstream equivalence: burrows_delta == acceptance_check Signal A on the same input (3-tuple)")

# 3. Gate no-op: the advisory module never enters the blocking path ------------
CLEAN = "The scanner loads the rules from the shared module, so the hook and the checker cannot drift."
with tempfile.TemporaryDirectory() as td:
    env = {**os.environ, "VOICE_LEARNED_DIR": td, "VOICE_GATE_LOG": str(pathlib.Path(td, "gate.log")),
           "VOICE_GATE_VECTOR": "off"}
    r = subprocess.run([sys.executable, "-I", str(PLUGIN_DIR / "hooks" / "gate.py"), "--surface", "public"],
                       input=CLEAN, capture_output=True, text=True, env=env)
    want = '{"status": "pass", "surface": "public", "tokens_to_model": 0}'
    ck(r.returncode == 0 and r.stdout.strip() == want,
       "gate no-op: clean-pass JSON byte-identical, no stylometry fields", r.stdout[:120])

# 4. Fail-open CLI: no reference at all -> exit 0, n/a, defined note ------------
with tempfile.TemporaryDirectory() as td:
    env = {**os.environ, "VOICE_LEARNED_DIR": td}
    r = subprocess.run([sys.executable, "-I", str(PLUGIN_DIR / "learn" / "voice_fit.py"), "-"],
                       input=fx["candidate_text"], capture_output=True, text=True, env=env)
    ck(r.returncode == 0 and r.stdout.startswith("voice fit: client sample vs candidate copy"),
       "fail-open: no profile and no samples still renders the advisory table, exit 0")
    ck(r.stdout.count("n/a") >= 2 and "no profile at" in r.stdout,
       "fail-open: reference columns read n/a with the defined note")
    rj = subprocess.run([sys.executable, "-I", str(PLUGIN_DIR / "learn" / "voice_fit.py"), "-", "--json"],
                        input=fx["candidate_text"], capture_output=True, text=True, env=env)
    j = json.loads(rj.stdout)
    ck(rj.returncode == 0 and j["sample"] is None and j["burrows_delta"]["copy"] is None
       and j["burrows_delta"]["sample_self"] is None and j["reference"] is None,
       "fail-open: --json carries null reference fields")
    ck(j["candidate"] == fx["voice_stats"],
       "fail-open: the candidate column stays exact without any reference")

# 5 + 6. Samples mode: spread rule + fixture parity through the CLI ------------
with tempfile.TemporaryDirectory() as td:
    tdp = pathlib.Path(td)
    env = {**os.environ, "VOICE_LEARNED_DIR": str(tdp / "learned")}
    (tdp / "learned").mkdir()
    samples = tdp / "samples"
    samples.mkdir()
    for i, text in enumerate(fx["sample_texts"]):
        (samples / f"s{i + 1}.md").write_text(text, encoding="utf-8")
    cand = tdp / "cand.md"
    cand.write_text(fx["candidate_text"], encoding="utf-8")
    one = tdp / "one"
    one.mkdir()
    (one / "only.md").write_text(fx["sample_texts"][0], encoding="utf-8")
    r1 = subprocess.run([sys.executable, "-I", str(PLUGIN_DIR / "learn" / "voice_fit.py"),
                         str(cand), "--samples", str(one)], capture_output=True, text=True, env=env)
    ck(r1.returncode == 0 and "sample-self n/a" in r1.stdout and "copy n/a" in r1.stdout,
       "spread rule: one sample document reads n/a on both delta columns")
    r3 = subprocess.run([sys.executable, "-I", str(PLUGIN_DIR / "learn" / "voice_fit.py"),
                         str(cand), "--samples", str(samples)], capture_output=True, text=True, env=env)
    ck(r3.returncode == 0 and "sample-self 0.53 (k 3, loo 0.48 to 0.59)" in r3.stdout
       and "copy n/a (candidate under 500 words" in r3.stdout and "lower = closer" in r3.stdout,
       "samples mode: the delta row pins the promoted goldens with k and loo range "
       "(was 'sample-self 1.19' + 'copy 0.67'); the 122-word candidate reads n/a under the owned floor (AM-02)")
    rj = subprocess.run([sys.executable, "-I", str(PLUGIN_DIR / "learn" / "voice_fit.py"),
                         str(cand), "--samples", str(samples), "--json"],
                        capture_output=True, text=True, env=env)
    j = json.loads(rj.stdout)
    ck(j["burrows_delta"]["copy"] is None
       and j["burrows_delta"]["sample_self"] == 0.5332771606692496
       and j["burrows_delta"]["sample_self_k"] == 3
       and j["candidate"] == fx["voice_stats"],
       "samples mode: --json pins the promoted sample-self row and the suppressed copy delta")

    # profile mode: build the real profile with build_voice_profile.py, then fit against it
    rbp = subprocess.run([sys.executable, "-I", str(PLUGIN_DIR / "learn" / "build_voice_profile.py"),
                          str(samples), "--out", str(tdp / "learned" / "profile.json")],
                         capture_output=True, text=True, env=env)
    prof = json.loads((tdp / "learned" / "profile.json").read_text(encoding="utf-8"))
    ck(rbp.returncode == 0 and prof.get("function_words", {}).get("docs") == 3,
       "profile mode setup: build_voice_profile builds a 3-document function_words profile")
    ck(isinstance(prof.get("battery"), dict) and prof["battery"].get("docs") == 3
       and isinstance(prof["battery"].get("measures"), dict) and prof["battery"]["measures"],
       "profile mode setup: the profile carries the 74-measure battery section")
    rp = subprocess.run([sys.executable, "-I", str(PLUGIN_DIR / "learn" / "voice_fit.py"),
                         str(cand), "--profile", str(tdp / "learned" / "profile.json"), "--json"],
                        capture_output=True, text=True, env=env)
    jp = json.loads(rp.stdout)
    delta_ok = jp["burrows_delta"]["copy"] is None and "under 500 words" in " ".join(jp["notes"])
    ck(rp.returncode == 0 and delta_ok and jp["reference"] == "profile",
       "profile mode: the 122-word candidate reads n/a with the owned-floor note, reference=profile")
    sample_ok = (jp["sample"] is not None
                 and jp["sample"]["word count"] == prof.get("words")
                 and jp["sample"]["sentence length p95"] == prof.get("sentence_length", {}).get("p95"))
    ck(sample_ok, "profile mode: the sample column maps from profile.json aggregates")

# 6. Tokenizer tolerance: digit runs are the documented divergence -------------
dg = vf.voice_stats(fx["digit_case"]["text"])
ck(dg["word count"] == fx["digit_case"]["js_word_count"] + fx["digit_case"]["digit_runs"]
   and dg["sentences"] == fx["digit_case"]["js_sent_words"],
   "tokenizer tolerance: WORD_RE counts digit runs the sitefactory tokenizer skips (documented)")

# 7. stdlib-only: module imports never leave the stdlib set --------------------
tree = ast.parse((PLUGIN_DIR / "learn" / "voice_fit.py").read_text(encoding="utf-8"))
imported = set()
for node in ast.walk(tree):
    if isinstance(node, ast.Import):
        imported.update(a.name.split(".")[0] for a in node.names)
    elif isinstance(node, ast.ImportFrom) and node.module:
        imported.add(node.module.split(".")[0])
ck(imported <= ALLOWED_IMPORTS, "stdlib-only: imports stay in the stdlib set", str(sorted(imported)))

print(f"\nvoice_fit contract: {len(fails)} failure(s)")
sys.exit(1 if fails else 0)
