#!/usr/bin/env python3
"""Regenerate the README MCP tool table from the derived tool registry.

The MCP tool docs cannot drift from code: this script imports the same
derivation the stdio server uses (``mcp-server/server.py`` reads each
script's ``MCP_SURFACE`` table), renders the table between the marked
block in ``uxr-plugin/README.md``, and ``--check`` exits 1 when the
committed README no longer matches. Run it after changing a script's
flags. Stdlib only; no network.

Usage:

    python scripts/gen_mcp_docs.py            # rewrite the marked block
    python scripts/gen_mcp_docs.py --check    # verify only; exit 1 on drift
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

PLUGIN_ROOT = Path(__file__).resolve().parent.parent
README_PATH = PLUGIN_ROOT / "README.md"
SERVER_PATH = PLUGIN_ROOT / "mcp-server" / "server.py"

BEGIN = "<!-- BEGIN auto-generated MCP tool table (scripts/gen_mcp_docs.py) -->"
END = "<!-- END auto-generated MCP tool table (scripts/gen_mcp_docs.py) -->"


def _load_server():
    spec = importlib.util.spec_from_file_location("uxr_mcp_server_gen", SERVER_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _args_summary(tool: dict) -> str:
    """One line describing the tool's derived arguments."""
    surface = tool["surface"]
    parts: list[str] = []
    sub = surface.get("subcommand")
    if sub:
        parts.append("`" + sub["name"] + "`: " + " | ".join(sub["values"]))
    for entry in surface.get("flags", []):
        label = entry.get("flag", entry["name"])
        kind = entry.get("type", "string")
        if entry.get("kind") == "positional":
            parts.append(f"`{entry['name']}` ({kind}"
                         + (", required" if entry.get("required") else "") + ")")
        else:
            parts.append(f"`{label}` <{kind}>"
                         + (" repeat" if entry.get("repeat") else "")
                         + (" required" if entry.get("required") else ""))
    for entry in surface.get("switches", []):
        parts.append(f"`{entry['flag']}`")
    stdin = surface.get("stdin")
    if stdin:
        parts.append(f"`{stdin['name']}` (string, required)" if stdin.get("required")
                     else f"`{stdin['name']}` (string)")
    return ", ".join(parts) if parts else "none"


def render_table() -> str:
    """The generated markdown block, markers included."""
    lines = [BEGIN, "", "Generated by `scripts/gen_mcp_docs.py` from each script's "
             "`MCP_SURFACE` table; run it after changing a script's flags. "
             "`tools/list` serves JSON Schemas derived from the same tables.", "",
             "| Tool | Script | Arguments |",
             "|---|---|---|"]
    for tool in _load_server().get_registry().values():
        script = f"`scripts/{tool['name']}.py`"
        lines.append(f"| `{tool['name']}` | {script} | {_args_summary(tool)} |")
    lines += ["", END, ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gen_mcp_docs.py",
        description="Regenerate the README MCP tool table from the derived registry.")
    parser.add_argument("--check", action="store_true",
                        help="verify the committed block matches; exit 1 on drift")
    opts = parser.parse_args(list(sys.argv[1:] if argv is None else argv))
    block = render_table()
    readme = README_PATH.read_text(encoding="utf-8")
    start = readme.find(BEGIN)
    end = readme.find(END)
    if start == -1 or end == -1 or end < start:
        print("README.md is missing the auto-generated table markers; "
              f"expected {BEGIN!r} ... {END!r}")
        return 1
    current = readme[start:end + len(END)]
    if opts.check:
        if current == block.rstrip("\n"):
            print("docs drift check: README matches the derived registry")
            return 0
        print("docs drift: README tool table differs from the derived registry; "
              "run python scripts/gen_mcp_docs.py")
        return 1
    if current == block.rstrip("\n"):
        print("README tool table already matches the derived registry; nothing written")
        return 0
    updated = readme[:start] + block + readme[end + len(END):]
    README_PATH.write_text(updated, encoding="utf-8", newline="\n")
    print(f"wrote the MCP tool table into {README_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
